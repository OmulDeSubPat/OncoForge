export const timelineFrames: TimelineFrame[] = candidates.map((candidate, index) => {
  const deltaPic50 = index === 0 ? 0.9 : Math.round((candidate.metrics.pic50 - candidates[index - 1].metrics.pic50) * 100) / 100;
  const deltaScore = index === 0 ? 0 : Math.round((candidate.score - candidates[index - 1].score) * 100) / 100;
  return {
    generation: candidate.round,
    candidateId: candidate.id,
    parentId: candidate.parent,
    mutation: candidate.mutation,
    deltaPic50,
    deltaScore,
    reward: candidate.metrics.verifiableReward,
    verifiedReward: candidate.metrics.verifiableReward,
    toxicityPenalty: Number((candidate.metrics.toxicity * 0.35).toFixed(2)),
    invalidPenalty: Number((candidate.metrics.pains * 0.25).toFixed(2)),
    uncertaintyPenalty: Number((candidate.metrics.uncertainty * 0.4).toFixed(2)),
    exploration: Number((0.42 - index * 0.03).toFixed(2)),
    exploitation: Number((0.58 + index * 0.03).toFixed(2)),
  };
});

